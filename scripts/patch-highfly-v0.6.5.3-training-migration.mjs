import fs from 'node:fs';

function read(path) {
  return fs.readFileSync(path, 'utf8');
}

function write(path, content) {
  fs.writeFileSync(path, content, 'utf8');
  console.log(`[HIGHFLY v0.6.5.3] patched ${path}`);
}

function replaceRequired(source, pattern, replacement, label) {
  if (!pattern.test(source)) throw new Error(`Anchor not found: ${label}`);
  return source.replace(pattern, replacement);
}

// ---------------------------------------------------------------------------
// TRAINING ROUTINE MIGRATION / SAFE FALLBACK
// v0.6.5 replaced the old generic routine catalog with the authored D1-D5
// HIGHFLY split, while draftForRoutine still hard-coded "HIGHFLY HÍBRIDO" as
// its fallback. On a fresh boot that key no longer exists, so the world-entry
// path attempted undefined.map(...) while installing Training and the generic
// renderer guard surfaced the failure as "reading 'map'".
//
// Make the catalog itself authoritative. Old/local drafts are migrated to the
// first currently valid routine and a malformed/empty draft can never make the
// boot path map over undefined.
// ---------------------------------------------------------------------------
{
  const path = 'src/highfly/training_ui.ts';
  let source = read(path);

  source = replaceRequired(
    source,
    /function draftForRoutine\(name: string\): WorkoutDraft \{[\s\S]*?\n\}\n\nfunction storageKey/,
    `function validRoutineName(value: unknown): string {\n  const candidate = typeof value === 'string' ? value : '';\n  if (candidate && Object.prototype.hasOwnProperty.call(ROUTINES, candidate)) return candidate;\n  return Object.keys(ROUTINES)[0] ?? '';\n}\n\nfunction routineRows(name: string): readonly string[] {\n  const valid = validRoutineName(name);\n  return ROUTINES[valid] ?? [];\n}\n\nfunction draftForRoutine(name: string): WorkoutDraft {\n  const routine = validRoutineName(name);\n  return {\n    version: 1,\n    dayKey: dayKeyLocal(),\n    startedAt: null,\n    routine,\n    rows: routineRows(routine).map(defaultRow),\n  };\n}\n\nfunction storageKey`,
    'safe routine resolver',
  );

  source = replaceRequired(
    source,
    /function loadDraft\(world: HighflyTrainingWorld\): WorkoutDraft \{[\s\S]*?\n\}\n\nfunction saveDraft/,
    `function loadDraft(world: HighflyTrainingWorld): WorkoutDraft {\n  try {\n    const raw = localStorage.getItem(storageKey(world));\n    if (raw) {\n      const parsed = JSON.parse(raw) as WorkoutDraft;\n      if (parsed.version === 1 && parsed.dayKey === dayKeyLocal() && Array.isArray(parsed.rows)) {\n        const routine = validRoutineName(parsed.routine);\n        const rows = parsed.rows.length > 0 ? parsed.rows : routineRows(routine).map(defaultRow);\n        return { ...parsed, routine, rows };\n      }\n    }\n  } catch { /* fresh draft */ }\n  return draftForRoutine(validRoutineName(null));\n}\n\nfunction saveDraft`,
    'stored routine migration',
  );

  write(path, source);
}

// Regression contract: this is deliberately textual because training_ui.ts is
// generated by the overlay chain. The runtime smoke remains the authoritative
// end-to-end proof that Appearance -> Class -> World actually boots.
{
  const path = 'tests/highfly_v0653_training_migration.test.ts';
  const content = `import fs from 'node:fs';\nimport { describe, expect, it } from 'vitest';\n\ndescribe('HIGHFLY v0.6.5.3 training routine migration', () => {\n  it('never maps an absent legacy routine during world entry', () => {\n    const source = fs.readFileSync('src/highfly/training_ui.ts', 'utf8');\n    expect(source).toContain('function validRoutineName(value: unknown): string');\n    expect(source).toContain("Object.prototype.hasOwnProperty.call(ROUTINES, candidate)");\n    expect(source).toContain('return ROUTINES[valid] ?? []');\n    expect(source).toContain('rows: routineRows(routine).map(defaultRow)');\n    expect(source).toContain('const routine = validRoutineName(parsed.routine)');\n    expect(source).not.toContain("ROUTINES['HIGHFLY HÍBRIDO']).map");\n  });\n});\n`;
  write(path, content);
}

console.log('[HIGHFLY v0.6.5.3] training routine migration guard applied.');
